def _spread_words(seed: list[str], *, duration_s: float, wpm: float, filler: str) -> list[tuple[str, float, float]]:
    """Timestamps spanning duration_s so min_evidence can pass without a long WAV."""
    interval = 60.0 / wpm
    n = max(1, int(duration_s / interval))
    words: list[tuple[str, float, float]] = []
    for i in range(n):
        start = i * interval
        token = filler if i % max(1, int(wpm / 2)) == 0 else seed[i % len(seed)]
        words.append((token, start, start + interval * 0.8))
    return words


def _transcript(language: str, words: list[tuple[str, float, float]], *, mean_prob: float) -> dict[str, Any]:
    text = " ".join(w[0] for w in words[:12])
    duration = words[-1][2] if words else 1.0
    return {
        "language": language,
        "duration": duration,
        "mean_word_probability": mean_prob,
        "model": "synthetic-golden",
        "segments": [
            {
                "id": 0,
                "start": words[0][1] if words else 0.0,
                "end": duration,
                "text": text,
                "words": [{"word": w, "start": s, "end": e, "probability": mean_prob} for w, s, e in words],
            }
        ],
    }


