def _strip_volatile(result: dict[str, Any]) -> dict[str, Any]:
    prov = dict(result.get("provenance") or {})
    prov["generated_at"] = "1970-01-01T00:00:00Z"
    out = dict(result)
    out["provenance"] = prov
    out["insights"] = {
        "summary": "",
        "strengths": [],
        "weaknesses": [],
        "opportunities": [],
    }
    return out


def write_fixture(spec: dict[str, Any], *, expected: dict[str, Any] | None = None) -> Path:
    directory = GOLDEN_ROOT / spec["id"]
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "expected").mkdir(exist_ok=True)
    write_sine_wav(
        directory / "audio.wav",
        duration_s=1.0,
        freq_hz=440.0 if spec["language"] == "en" else 392.0,
        noise=spec["noise"],
    )
    transcript = _transcript(spec["language"], spec["words"], mean_prob=spec["mean_prob"])
    (directory / "transcript.json").write_text(json.dumps(transcript, indent=2) + "\n")
    (directory / "metrics.json").write_text(
        json.dumps(_metrics(confidence=spec["confidence"], wpm=spec["wpm"], fillers=spec["fillers"]), indent=2)
        + "\n"
    )
    (directory / "audio_metrics.json").write_text(
        json.dumps(
            {
                "duration_s": 180.0,
                "voiced_s": 90.0,
                "voiced_ratio": 0.5,
                "snr_db": spec["snr_db"],
                "music_flag": False,
                "noise_flag": spec["noise_flag"],
                "pvq_windows": [{"start": 0, "value": 0.18}],
            },
            indent=2,
        )
        + "\n"
    )
    (directory / "manifest.json").write_text(
        json.dumps(
            {
                "id": spec["id"],
                "session_id": spec["session_id"],
                "language": spec["language"],
                "kind": spec["kind"],
                "origin": spec["origin"],
                "license": spec["license"],
                "audio": "audio.wav",
            },
            indent=2,
        )
        + "\n"
    )
    if expected is not None:
        (directory / "expected" / "analysis_result.json").write_text(
            json.dumps(_strip_volatile(expected), indent=2) + "\n"
        )
    return directory


def run_fusion_for(spec: dict[str, Any], output_dir: Path | None = None) -> dict[str, Any]:
    from tempfile import TemporaryDirectory

    from pipeline.stages.fusion_scoring import run_fusion_scoring

    directory = GOLDEN_ROOT / spec["id"]

    def _run(dest: Path) -> dict[str, Any]:
        return run_fusion_scoring(
            session_id=spec["session_id"],
            output_dir=dest,
            context_type="keynote",
            language=spec["language"],
            camera_setup="audio_only",
            packages_dir=PACKAGES,
            transcript_path=directory / "transcript.json",
            metrics_path=directory / "metrics.json",
            audio_metrics_path=directory / "audio_metrics.json",
        )

    if output_dir is not None:
        return _run(output_dir)
    with TemporaryDirectory() as tmp:
        return _run(Path(tmp))


def write_all(*, with_expected: bool = True) -> list[Path]:
    written: list[Path] = []
    for spec in fixtures():
        write_fixture(spec)
        expected = run_fusion_for(spec) if with_expected else None
        write_fixture(spec, expected=expected)
        written.append(GOLDEN_ROOT / spec["id"])
    return written
