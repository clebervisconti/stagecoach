def _metric(metric_id: str, value: float, unit: str, confidence: float) -> dict[str, Any]:
    return {
        "id": metric_id,
        "value": value,
        "unit": unit,
        "basis": "heuristic" if metric_id.startswith(("pp_", "vv_", "tm_")) else "research",
        "source": "S12" if metric_id.startswith("fl_") else "H",
        "confidence": confidence,
        "applicable": True,
    }


